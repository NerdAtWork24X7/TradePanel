#!/usr/bin/env node
/*
 * Build the icon registries from the vendored SVGs in `frontend/web/icons`.
 *
 * Two artifacts are written so the vanilla chart workspace and the bundled
 * Tauri shell share one source of truth:
 *
 *   web/icons.js           — browser global `OTIcons` (all vendored icons)
 *   src/lib/icons-data.ts  — tree-shake-friendly data for the shell bundle
 *
 * SVG files only contribute their `viewBox` and inner markup; colour always
 * comes from `currentColor` so a single asset works in both themes.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const ICON_DIR = join(ROOT, "web", "icons");
const WEB_OUT = join(ROOT, "web", "icons.js");
const SHELL_OUT = join(ROOT, "src", "lib", "icons-data.ts");

/** Icons referenced by shell components; keeps the bundle small. */
const SHELL_ICONS = [
  // brand + chrome
  "tp-logo", "tp-chevron-left", "tp-chevron-right", "tp-chevron-down",
  "tp-sun", "tp-moon", "tab-close", "scr-refresh", "chart-reset-view",
  "st-snapshot-open-in-new-tab", "header-settings", "header-fullscreen-mode", "scr-panel-fullscreen",
  "ot-header-group", "scr-add", "scr-save", "scr-trash", "scr-check",
  "menu-manage-layouts-rename", "uc-search",
  // AI panel
  "ai-sparkle", "ai-send", "ai-stop", "ai-thumb-up", "ai-thumb-down",
  "uc-new-chat", "uc-settings", "draw-text",
  // settings page sections
  "settings-general", "settings-network", "settings-service", "settings-alerts",
  "header-indicators-metrics-and-strategies", "dt-cm-lock", "dt-add-alert", "update-app-download",
  "settings-about", "settings-agents", "profile-keyboard", "profile-help",
  // chart/drawing fallbacks used by the snapshot + shared markup
  "draw-cursor", "draw-trend-line", "draw-horizontal-line", "draw-rectangle",
  "draw-fib", "draw-brush", "draw-measure", "draw-position", "draw-short-position",
  "draw-magnet", "draw-hide-all-drawings", "draw-hide-all-mode-active",
  "draw-add-to-favorites", "draw-remove-from-favorites", "draw-lock",
  "draw-lock-drawings-active", "draw-hide-indicators", "draw-hide-indicators-active",
  "dt-settings", "dt-remove", "dt-line-tool-color", "dt-line-tool-width",
  "dt-style", "st-legend-eye-show", "st-legend-settings", "st-legend-remove",
  "st-legend-more", "chart-zoom-in", "chart-zoom-out", "chart-maximize",
  "chart-move", "chart-goto-realtime",
];

function parseSvg(file) {
  const raw = readFileSync(file, "utf8");
  const match = raw.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/i);
  if (!match) throw new Error(`No <svg> root in ${basename(file)}`);
  const attrs = match[1];
  const viewBox = (attrs.match(/\bviewBox="([^"]+)"/i) || [])[1] || "0 0 28 28";
  let body = match[2]
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (!body) throw new Error(`Empty icon: ${basename(file)}`);
  return { viewBox, body };
}

const files = readdirSync(ICON_DIR)
  .filter((name) => name.endsWith(".svg") && name !== "tp-app-icon.svg")
  .sort();
if (!files.length) throw new Error(`No SVG icons found in ${ICON_DIR}`);

const icons = {};
for (const file of files) {
  const name = basename(file, ".svg");
  const { viewBox, body } = parseSvg(join(ICON_DIR, file));
  icons[name] = { v: viewBox, b: body };
}

/* ── web/icons.js ─────────────────────────────────────────────────────── */
const webData = JSON.stringify(icons);
const web = `/* Generated by frontend/scripts/build-icons.mjs — do not edit.
 * Source SVGs: frontend/web/icons/*.svg (OpenTrader icon set, MIT — see
 * frontend/web/icons/LICENSE). */
(function (root) {
    'use strict';
    var ICONS = ${webData};
    var NAMES = Object.keys(ICONS);
    function svg(name, size, cls) {
        var icon = ICONS[name];
        if (!icon) return '';
        var px = size ? ' width="' + size + '" height="' + size + '"' : '';
        var c = cls ? ' class="' + cls + '"' : '';
        return '<svg viewBox="' + icon.v + '"' + px + c +
            ' fill="currentColor" aria-hidden="true" focusable="false">' + icon.b + '</svg>';
    }
    function el(name, size, cls) {
        var icon = ICONS[name];
        if (!icon) return null;
        var node = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
        node.setAttribute('viewBox', icon.v);
        if (size) { node.setAttribute('width', size); node.setAttribute('height', size); }
        if (cls) node.setAttribute('class', cls);
        node.setAttribute('fill', 'currentColor');
        node.setAttribute('aria-hidden', 'true');
        node.setAttribute('focusable', 'false');
        node.innerHTML = icon.b;
        return node;
    }
    var api = { names: NAMES, has: function (n) { return !!ICONS[n]; }, svg: svg, el: el, data: ICONS };
    if (typeof module === 'object' && module.exports) module.exports = api;
    root.OTIcons = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
writeFileSync(WEB_OUT, web);

/* ── src/lib/icons-data.ts ────────────────────────────────────────────── */
const shellIcons = {};
for (const name of SHELL_ICONS) {
  if (!icons[name]) throw new Error(`Shell icon missing: ${name}`);
  shellIcons[name] = icons[name];
}
const ts = `/* Generated by frontend/scripts/build-icons.mjs — do not edit.
 * Source SVGs: frontend/web/icons/*.svg (OpenTrader icon set, MIT — see
 * frontend/web/icons/LICENSE). */
export type IconRecord = { v: string; b: string };
export const ICON_DATA: Record<string, IconRecord> = ${JSON.stringify(shellIcons)};
`;
writeFileSync(SHELL_OUT, ts);

const size = statSync(WEB_OUT).size + statSync(SHELL_OUT).size;
console.log(`icons: ${files.length} svg → ${SHELL_ICONS.length} shell, ${(size / 1024).toFixed(1)} KiB generated`);
